export type MessageKey = keyof (typeof messages)['vi']

export function normalizeLanguage(value: unknown): UiLanguage {
  return value === 'en' ? 'en' : 'vi'
}

export function t(language: UiLanguage, key: MessageKey, variables?: Record<string, string | number>) {
  const safeLanguage = normalizeLanguage(language)
  const template = messages[safeLanguage][key] ?? messages.vi[key] ?? messages.en[key] ?? key
  if (!variables) return template

  return template.replace(/\{(\w+)\}/g, (_, token: string) => {
    const value = variables[token]
    return typeof value === 'undefined' ? `{${token}}` : String(value)
  })
}

export function formatPercent(value: number) {
  return Math.round(value * 10) / 10
}
